// SwiftUI exposes the system accessibility values as read-only environment
// keys.  The gallery still needs deterministic launch-argument variants, so
// previews use these private overrides and components combine them with the
// real system values.  Production views never set the overrides.
private struct SETReduceMotionOverrideKey: EnvironmentKey {
    static let defaultValue: Bool? = nil
}

private struct SETReduceTransparencyOverrideKey: EnvironmentKey {
    static let defaultValue: Bool? = nil
}

extension EnvironmentValues {
    var setReduceMotionOverride: Bool? {
        get { self[SETReduceMotionOverrideKey.self] }
        set { self[SETReduceMotionOverrideKey.self] = newValue }
    }

    var setReduceTransparencyOverride: Bool? {
        get { self[SETReduceTransparencyOverrideKey.self] }
        set { self[SETReduceTransparencyOverrideKey.self] = newValue }
    }
}
